/** @typedef {'en'|'tr'} Language */

/** Select the first supported browser preference, falling back to English.
 * @param {readonly string[]} languages Browser language tags in preference order.
 * @returns {Language}
 */
export function browserLanguage(languages) {
  for (const language of languages) {
    const base = language.toLowerCase().split("-")[0];
    if (base === "tr" || base === "en") return base;
  }
  return "en";
}

