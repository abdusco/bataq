/** Translate a UI message and interpolate named values without HTML injection.
 * @param {Language} language
 * @param {string} message English message used as the translation key.
 * @param {Record<string, string|number>} [values={}] Named placeholders.
 * @returns {string}
 */
export function translate(language, message, values = {}) {
  const text = language === "tr" ? TURKISH[message] || message : message;
  return text.replace(/\{(\w+)\}/g, (match, name) => (Object.hasOwn(values, name) ? String(values[name]) : match));
}
